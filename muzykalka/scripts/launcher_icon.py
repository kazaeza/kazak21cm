"""O-56 (ADR-055): the launcher icon from the thread (the math of ThreadBody.trace, settled, no plucks) as Android vector
drawables: foreground (ball and thread), background (ink with a warm glow), monochrome (the thread alone, themed icons).
Usage, from muzykalka/: python3 scripts/launcher_icon.py [out_dir]"""
import math, sys
# the fourth (4:3): a symmetric winding that reads as an emblem down to 48 dp; run from muzykalka/
P, Q, SPIN = 4, 3, 0.5
OUT = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/res/drawable"
N = 900
C, R = 54.0, 23.0          # centre and radius of the ball, dp of the 108 canvas (safe zone r 33)
s = 0.9
tilt = s * 0.62
ct, st = math.cos(tilt), math.sin(tilt)
pts = []
for i in range(N + 1):
    u = 2 * math.pi * i / N
    z0 = s * math.cos(Q * u)
    rho = math.sqrt(1 - z0 * z0)
    a = P * u + SPIN
    x, y0, z = rho * math.cos(a), rho * math.sin(a), z0
    y = y0 * ct - z * st
    zz = y0 * st + z * ct
    k = 1 / (1 - 0.16 * zz)
    # ball radius in trace units is 1 (scaled by k up to 1.19): fit 1.0 to R*0.93
    sc = R * 0.86
    pts.append((C + x * k * sc, C - y * k * sc, zz))
runs = {True: [], False: []}
cur, side = [pts[0]], None
for a, b in zip(pts, pts[1:]):
    front = a[2] + b[2] >= 0
    if side is None: side = front
    if front != side:
        runs[side].append(cur); cur = [a]; side = front
    cur.append(b)
runs[side].append(cur)
def path(rs):
    out = []
    for r in rs:
        if len(r) < 2: continue
        out.append("M%.2f,%.2f" % r[0][:2] + "".join(" L%.2f,%.2f" % p[:2] for p in r[1:]))
    return " ".join(out)
front, back = path(runs[True]), path(runs[False])
